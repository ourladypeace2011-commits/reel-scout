# -*- coding: utf-8 -*-
"""Serve a set of clips to a real device, one card each, labelled from ffprobe.

Why this is a committed script rather than a throwaway in /tmp: the 2026-08-25
investigation into why 103 of 109 library files would not play on an iPad needed
exactly this, got it wrong twice, and then threw it away.

Two of those mistakes are designed out here rather than written down:

1. **`python3 -m http.server` cannot be used for this.** It answers no byte-range
   requests, and iOS Safari refuses to play video from a server that does not.
   Every clip comes back "broken" -- a false negative for the entire run. The 206
   handling below is the load-bearing part of this file.

2. **A single-variable test has to be *readable* as single-variable.** The first
   run put the control and the first variant next to each other; they were the
   same video, so the two cards looked identical, and the first answer that came
   back ("(1) plays") turned out to be the control being tapped twice. Nothing
   was wrong with the design -- only with what a person could see. So every label
   here is generated by running `ffprobe` on the file being served, never typed
   in: a label cannot drift from the artifact it names if it is derived from it.

Usage::

    python3 scripts/codec-probe-server.py data/videos/a.mp4 data/videos/b.mp4
    python3 scripts/codec-probe-server.py --port 8503 --bind 0.0.0.0 clips/*.mp4

Then open ``http://<this-host>:<port>/`` on the device under test and tap each
card. The page reports what the browser itself said (`MediaError` code, decoded
resolution, duration), so the result does not depend on someone describing what
they saw.

This is a manual rig: it serves local files to a device on your own network, it
does not authenticate, and it is meant to be run for a few minutes and stopped.
"""
from __future__ import annotations

import argparse
import http.server
import json
import os
import re
import socket
import socketserver
import subprocess
import sys
from typing import Dict, List, Optional, Tuple

_RANGE_RE = re.compile(r"bytes=(\d*)-(\d*)")
_CHUNK = 262144


def parse_range(header: Optional[str], size: int) -> Tuple[int, int, bool]:
    """Resolve a Range header against a file size.

    Returns ``(start, end_inclusive, is_partial)``. A missing or unparseable
    header yields the whole file with ``is_partial=False``, and the caller sends
    200 rather than 206. ``start >= size`` is the caller's cue to send 416.

    Split out as a pure function on purpose: this is the one piece here whose
    silent failure looks exactly like "the device cannot decode this codec".
    """
    if not header:
        return 0, size - 1, False
    m = _RANGE_RE.match(header.strip())
    if not m:
        return 0, size - 1, False
    g1, g2 = m.group(1), m.group(2)
    if g1:
        start = int(g1)
        end = min(int(g2), size - 1) if g2 else size - 1
    elif g2:
        # Suffix form: "bytes=-500" asks for the last 500 bytes.
        start = max(0, size - int(g2))
        end = size - 1
    else:
        # "bytes=-" is neither; treat it as no range rather than as byte 0.
        return 0, size - 1, False
    return start, end, True


def probe(path: str) -> Dict[str, str]:
    """Ask ffprobe what actually landed.

    Never raises. An unprobeable clip is still worth serving; it just gets a
    label that says so, which is itself the useful information on the page.
    """
    out = {"video": "?", "audio": "?", "duration": "?", "size": ""}
    try:
        out["size"] = "%.1f MB" % (os.path.getsize(path) / 1048576.0)
    except OSError:
        pass
    try:
        raw = subprocess.check_output(
            ["ffprobe", "-v", "error", "-print_format", "json",
             "-show_streams", "-show_format", path],
            stderr=subprocess.STDOUT,
        )
        data = json.loads(raw.decode("utf-8", "replace"))
    except Exception as exc:  # ffprobe absent, not on PATH, unreadable file...
        out["video"] = "ffprobe failed (%s)" % type(exc).__name__
        return out
    for s in data.get("streams", []):
        kind = s.get("codec_type")
        if kind == "video" and out["video"] == "?":
            out["video"] = s.get("codec_name", "?")
        elif kind == "audio" and out["audio"] == "?":
            out["audio"] = s.get("codec_name", "?")
    try:
        out["duration"] = "%.1fs" % float(data.get("format", {}).get("duration", 0))
    except (TypeError, ValueError):
        pass
    return out


def card_label(path: str, info: Dict[str, str]) -> str:
    """The one line a person reads to tell two cards apart.

    Filename first, because two clips with identical codecs are told apart only
    by which file they are -- that was the failure mode. Codecs second, because
    that is usually the variable under test.
    """
    bits = [os.path.basename(path), "%s + %s" % (info["video"], info["audio"])]
    if info["duration"] != "?":
        bits.append(info["duration"])
    if info["size"]:
        bits.append(info["size"])
    return " · ".join(bits)


