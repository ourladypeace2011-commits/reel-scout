def build_page(clips: List[Tuple[str, str]]) -> bytes:
    """clips: list of ``(key, absolute path)``.

    Labels are probed per request rather than at startup, so swapping a file on
    disk changes the page without a restart.
    """
    parts = [PAGE_HEAD]
    for key, path in clips:
        parts.append(
            '<div class="card"><h2>%s</h2>'
            '<video data-k="%s" controls playsinline preload="metadata" src="/v/%s"></video>'
            '<div class="err" id="e_%s"></div></div>'
            % (card_label(path, probe(path)), key, key, key)
        )
    parts.append(PAGE_TAIL)
    return "\n".join(parts).encode("utf-8")


def make_handler(clips: List[Tuple[str, str]]):
    by_key = dict(clips)

    class Handler(http.server.BaseHTTPRequestHandler):
        protocol_version = "HTTP/1.1"

        def log_message(self, fmt, *args):
            pass

        def do_GET(self):
            if self.path in ("/", "/index.html"):
                body = build_page(clips)
                self.send_response(200)
                self.send_header("Content-Type", "text/html; charset=utf-8")
                self.send_header("Content-Length", str(len(body)))
                self.send_header("Cache-Control", "no-store")
                self.end_headers()
                self.wfile.write(body)
                return
            if self.path.startswith("/v/"):
                path = by_key.get(self.path[3:])
                if path is None:
                    self.send_error(404)
                    return
                self._serve(path)
                return
            self.send_error(404)

        def _serve(self, path):
            try:
                size = os.path.getsize(path)
            except OSError:
                self.send_error(404)
                return
            start, end, partial = parse_range(self.headers.get("Range"), size)
            if start >= size:
                self.send_response(416)
                self.send_header("Content-Range", "bytes */%d" % size)
                self.send_header("Content-Length", "0")
                self.end_headers()
                return
            length = end - start + 1
            self.send_response(206 if partial else 200)
            self.send_header("Content-Type", "video/mp4")
            self.send_header("Accept-Ranges", "bytes")
            self.send_header("Content-Length", str(length))
            if partial:
                self.send_header("Content-Range", "bytes %d-%d/%d" % (start, end, size))
            self.end_headers()
            with open(path, "rb") as f:
                f.seek(start)
                left = length
                while left > 0:
                    chunk = f.read(min(_CHUNK, left))
                    if not chunk:
                        break
                    try:
                        self.wfile.write(chunk)
                    except (BrokenPipeError, ConnectionResetError):
                        return
                    left -= len(chunk)

    return Handler


class Server(socketserver.ThreadingTCPServer):
    allow_reuse_address = True
    daemon_threads = True


def _lan_ip() -> str:
    """Best-effort address to print. Nothing depends on it being right."""
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        s.connect(("8.8.8.8", 80))
        return s.getsockname()[0]
    except OSError:
        return "127.0.0.1"
    finally:
        s.close()


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Serve clips to a device, one card each.")
    ap.add_argument("clips", nargs="+", help="video files to serve, one card each")
    ap.add_argument("--port", type=int, default=8503)
    ap.add_argument("--bind", default="0.0.0.0")
    args = ap.parse_args(argv)

    missing = [c for c in args.clips if not os.path.isfile(c)]
    if missing:
        # Loudly, before binding. A missing clip would otherwise become a 404
        # card that reads exactly like "this device cannot play it".
        sys.stderr.write("not found:\n  %s\n" % "\n  ".join(missing))
        return 2

    clips = [("c%d" % i, os.path.abspath(p)) for i, p in enumerate(args.clips)]
    print("codec probe:", flush=True)
    for key, path in clips:
        print("  %s" % card_label(path, probe(path)), flush=True)
    print("\n  http://%s:%d/   (Ctrl-C to stop)" % (_lan_ip(), args.port), flush=True)
    Server((args.bind, args.port), make_handler(clips)).serve_forever()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
